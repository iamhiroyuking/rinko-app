-- 回が進んだページ範囲を持たせる
--
-- ログのページ範囲（「この発言はp.47-60について」）とは別物。こちらは
-- 「この回はどこからどこまで進んだか」を回そのものに記録する。
-- 欠席したメンバーがSeminarViewを見るだけで進み具合を追えるようにするため。
--
-- 開始だけを先に埋めておける運用も想定している。前回の回が終わったときに
-- 次の回を作り、担当者と開始ページ（次はここから、の意味）だけ書いておき、
-- 実際にその回が終わったら終了ページを追記する。
--
-- 更新ポリシーは既存の "editors can update units" がそのままこの2列にも
-- 及ぶ（deleted_at 以外の列は編集者なら誰でも変更できる設計のため、
-- 新しい列を追加するだけでよい）。
-- ---------------------------------------------------------------------------

alter table public.units
  add column page_from integer,
  add column page_to   integer;
