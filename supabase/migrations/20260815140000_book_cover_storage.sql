-- ---------------------------------------------------------------------------
-- 教材の表紙を手元の画像から選べるようにする
--
-- これまで cover_image_url にはURLを貼るしかなく、手元の写真を使えなかった
-- （docs/open-questions.md の「表紙画像の入手方法」。ここで決着）。
--
-- 保存先は新しいバケットを作らず log-images を使い回し、
-- <book_id>/cover/<uuid>.jpg に置く。理由は2つ。
--
-- 1. ストレージのポリシーはパスの先頭の教材idだけを見ているので、
--    そのまま効く。バケットを増やすと同じポリシーを書き直すことになる
-- 2. 教材を完全削除したときの後片付け（removeBookImages）が
--    <book_id>/ の下をすべて消すので、表紙も自動で消える。
--    別バケットにすると片付けを書き足すことになり、#53 で踏んだ
--    「消し忘れたファイルが容量を食う」を作り直しかねない
--
-- バケット名が log-images のままなのは実態より狭い。ただし名前を変えるには
-- 作り直しと移動が要るので、広い意味（教材の画像）で使うことにする。
--
-- 列は cover_image_url とは別に足す。URLとパスは別物で、ひとつの列に
-- 両方を入れると「どちらが入っているか」を毎回判定することになる。
-- attachments の file_url を storage_path に直したのと同じ理由。
-- ---------------------------------------------------------------------------

alter table public.books
  add column cover_storage_path text;
