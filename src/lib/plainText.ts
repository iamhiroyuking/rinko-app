/**
 * Markdownの記号を落として、素の文章にする。
 *
 * 検索結果の抜粋で使う。本文はMarkdownとして描画される（#113）が、
 * 抜粋は一致した箇所を強調するために文字列のまま扱う。そのため
 * `**正則化**` のように記号がそのまま並んでしまっていた。
 *
 * **完全なMarkdownの解釈はしない。** ここでやりたいのは「読める文章に
 * 見せる」ことだけで、描画は `LogBody` の仕事。記法を取りこぼしても
 * 記号が少し残るだけで、壊れはしない。
 *
 * 抜粋にしか使わないので、一致位置の計算もこの結果に対して行う。
 * 記号そのものを検索した場合（`**` など）は当たらなくなるが、
 * その語で探す場面は考えにくい。
 */
export function toPlainText(markdown: string): string {
  return (
    markdown
      // コードブロックは中身ごと落とす。抜粋に出しても読めない
      .replace(/```[\s\S]*?```/g, ' ')
      .replace(/`([^`]*)`/g, '$1')
      // 画像は代替文字だけ残す。リンクより先に処理する（記法が入れ子のため）
      .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
      .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
      // 行頭の記号。見出し・引用・箇条書き・番号付き
      .replace(/^\s{0,3}#{1,6}\s+/gm, '')
      .replace(/^\s{0,3}>\s?/gm, '')
      .replace(/^\s{0,3}[-*+]\s+/gm, '')
      .replace(/^\s{0,3}\d+\.\s+/gm, '')
      // 強調。長いものから順に消す
      .replace(/\*\*\*([^*]+)\*\*\*/g, '$1')
      .replace(/\*\*([^*]+)\*\*/g, '$1')
      .replace(/\*([^*]+)\*/g, '$1')
      .replace(/__([^_]+)__/g, '$1')
      // 区切り線
      .replace(/^\s{0,3}([-*_])\s*(?:\1\s*){2,}$/gm, ' ')
      // 改行も含めて空白をひとつに畳む。抜粋は1行で見せる
      .replace(/\s+/g, ' ')
      .trim()
  )
}
